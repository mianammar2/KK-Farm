#!/usr/bin/env python3
"""D-266 step 5c: classify every action (gate) by the app it belongs to and the level it needs, and write config/kkfarm_levels.php.
Levels: view < contribute < edit < manage. Run from apps/kk-farm after php artisan tinker dumped the gate list to /tmp/gates.json (see the D-266 notes).
The file is meant to be edited by hand afterwards: it is the single place that says what level an action is."""
import json, re, os, collections
d = json.load(open('/tmp/gates.json'))
AREA = {}
for r in d['rows']:
    gs = r['g'] if isinstance(r['g'], list) else ([r['g']] if r['g'] else [])
    m = r['m'][0] if isinstance(r['m'], list) else r['m']
    for g in gs:
        if m: AREA.setdefault(g, collections.Counter())[m] += 1
area = {g: c.most_common(1)[0][0] for g, c in AREA.items()}
MANUAL = {
 'health': 'health_checkup health_entry report_concern give_care see_health_history mark_antimicrobials manage_disease_control correct_health_records keep_vet_masters check_teeth record_height manage_medicine_store report_death approve_death',
 'breeding': 'record_heat record_mating manage_breeding cull_breeding',
 'goats': 'edit_goats remove_goats see_goat_pedigree exit_animal configure_intake see_recovery_progress',
 'weights': 'review_weights select_breeders',
 'feeding': 'approve_feeding_plan plan_rations release_feed_lots set_feed_lot_limits',
 'feed_cost': 'review_feed_pens set_feed_cost_settings',
 'sheds': 'manage_sheds set_pen_status approve_movements',
 'inventory': 'manage_general_store',
 'milking': 'manage_milking manage_milk_quality manage_milk_processing test_milk_lots handle_milk_money record_milk_processing',
 'purchase': 'manage_purchase',
 'sales': 'manage_sales manage_market approve_sale_orders',
 'animal_purchase': 'receive_goat_lot approve_goat_purchase request_goat_purchase',
 'tasks': 'manage_checklists assign_tasks see_all_tasks resolve_incidents',
 'fodder': 'manage_fodder_setup release_fodder record_fodder_work switch_fodder',
 'environment': 'manage_waste_routes lead_environment set_heat_limit approve_water_safe',
 'fattening': 'supervise_fattening settle_fattening',
 'welfare': 'manage_welfare_cases authorise_end_of_life',
 'quality': 'settle_quality_costs',
 'dashboard': 'see_security_log override_separation',
}
for a, names in MANUAL.items():
    for g in names.split(): area.setdefault(g, a)
LOCKED = {'clinical', 'open_cases', 'approve_breeding'}  # vet-locked: never part of a level
EDIT = {'edit_goats', 'manage_general_store', 'plan_rations', 'manage_feed_store', 'correct_health_records', 'set_pen_status', 'review_weights', 'review_feed_pens', 'select_breeders', 'manage_welfare_cases', 'lead_environment', 'resolve_incidents', 'handle_water_issues', 'manage_milk_lots', 'manage_maintenance_jobs'}
def level(g):
    if g.startswith('see_'): return 'view'
    if g in EDIT: return 'edit'
    if re.match(r'(manage|approve|authorise|configure|set|switch|settle|supervise|mark|keep|override|remove|exit|cull|release|assign|receive|request_end|select)_', g) or g in ('exit_animal', 'assign_tags'): return 'manage' if not g.startswith(('request', 'receive', 'assign_tags')) else 'contribute'
    return 'contribute'
ADMIN_ONLY = {g for g, r in d['roles'].items() if r == ['ceo']}  # Administrator-only by design: not part of any level (they would make every role read 'Custom')
gates = [g for g in d['gates'] if g not in LOCKED and g not in ADMIN_ONLY]
missing = [g for g in gates if g not in area]
if missing: raise SystemExit('no area for: ' + ', '.join(missing))
lines = ['<?php', '', '/*', ' * D-266 step 5c: what each action needs. \'area\' = the app it belongs to; \'level\' = view < contribute < edit < manage.', ' * A role\'s level in an app is read from the actions it holds (Levels::current) and a level picked on Access Tools → Levels ticks exactly those actions.',
         ' * Vet-locked actions (clinical, open_cases, approve_breeding) are not here: they stay fixed for roles and are given to one person only.', ' * Generated by docs/decisions/D-266/scripts/gen_levels.py; edit by hand afterwards.', ' */', '', 'return [']
for g in gates: lines.append(f"    '{g}' => ['area' => '{area[g]}', 'level' => '{level(g)}'],")
lines.append('];')
open('config/kkfarm_levels.php', 'w').write('\n'.join(lines) + '\n')
c = collections.Counter(level(g) for g in gates)
print(len(gates), 'actions classified', dict(c), '; administrator-only left out:', sorted(ADMIN_ONLY))
